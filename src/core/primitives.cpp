void Primitives::GeneratePlane(std::vector<Vertex>& vertices, std::vector<unsigned int>& indices, int segments) {
    // For a simple 1x1 plane (2 triangles)
    vertices = {
        // Position              // Normal         // TexCoords
        { { 0.5f, 0.0f,  0.5f},  {0.0f, 1.0f, 0.0f}, {1.0f, 1.0f} }, // Top-right
        { { 0.5f, 0.0f, -0.5f},  {0.0f, 1.0f, 0.0f}, {1.0f, 0.0f} }, // Bottom-right
        { {-0.5f, 0.0f, -0.5f},  {0.0f, 1.0f, 0.0f}, {0.0f, 0.0f} }, // Bottom-left
        { {-0.5f, 0.0f,  0.5f},  {0.0f, 1.0f, 0.0f}, {0.0f, 1.0f} }  // Top-left
    };

    indices = {
        0, 1, 3, // first triangle
        1, 2, 3  // second triangle
    };

    // Calculate Tangents and Bitangents for the plane for proper normal mapping
    // For a simple XY plane, T is along X, B is along -Z
    glm::vec3 tangent(1.0f, 0.0f, 0.0f);
    glm::vec3 bitangent(0.0f, 0.0f, -1.0f);
    for(auto& vertex : vertices) {
        vertex.Tangent = tangent;
        vertex.Bitangent = bitangent;
    }
}


